  function normalizeWs(s) {
    return String(s).replace(/\s+/g, " ").trim();
  }

  var SRC_TO_KEY = {};   // aniq moslik (raw text -> key)
  var NORM_TO_KEY = {};  // normalashtirilgan moslik (whitespace collapse -> key)

  function indexSource(srcLang) {
    var d = STRINGS[srcLang];
    if (!d) return;
    for (var k in d) {
      if (!Object.prototype.hasOwnProperty.call(d, k)) continue;
      var v = d[k];
      if (typeof v !== "string" || !v.trim()) continue;
      if (!(v in SRC_TO_KEY)) SRC_TO_KEY[v] = k;
      var nk = normalizeWs(v);
      if (!(nk in NORM_TO_KEY)) NORM_TO_KEY[nk] = k;
    }
  }
  indexSource("ru");
  indexSource("en");

  // Manba matnni (ru yoki en) maqsadli tilga tarjima qiladi.
  // Mos keladigan kalit topilmasa — matn o'zgarishsiz qaytariladi.
  function translateText(text, lang) {
    if (typeof text !== "string") return text;
    if (text in SRC_TO_KEY) return t(SRC_TO_KEY[text], lang);
    var nk = normalizeWs(text);
    if (nk in NORM_TO_KEY) return t(NORM_TO_KEY[nk], lang);
    return text;
  }

