  var LAT_TO_CYR = {
    "a":"а","b":"б","d":"д","e":"е","f":"ф","g":"г","h":"ҳ","i":"и",
    "j":"ҷ","k":"к","l":"л","m":"м","n":"н","o":"о","p":"п","q":"қ",
    "r":"р","s":"с","t":"т","u":"у","v":"в","x":"х","y":"й","z":"з",
    "A":"А","B":"Б","D":"Д","E":"Е","F":"Ф","G":"Г","H":"Ҳ",
    "I":"И","J":"Ҷ","K":"К","L":"Л","M":"М","N":"Н","O":"О","P":"П",
    "Q":"Қ","R":"Р","S":"С","T":"Т","U":"У","V":"В","X":"Х","Y":"Й","Z":"З"
  };

  function latWordToCyr(word) {
    var w = word;
    // Maxsus 2-belgili kombinatsiyalarni avval (apostrof bilan)
    w = w.replace(/o'/g, "Ў-KEEPER").replace(/g'/g, "Ғ-KEEPER")
         .replace(/O'/g, "Ў-KEEPER").replace(/G'/g, "Ғ-KEEPER");
    // boshqa ko'p-belgili kombinatsiyalar
    w = w.replace(/sh/gi, function(m){ return m === m.toUpperCase() ? "Ш" : "ш"; });
    w = w.replace(/ch/gi, function(m){ return m === m.toUpperCase() ? "Ч" : "ч"; });
    w = w.replace(/ng/gi, function(m){ return m === m.toUpperCase() ? "Нг" : "нг"; });
    w = w.replace(/ya/gi, function(m){ return m === m.toUpperCase() ? "Я" : "я"; });
    w = w.replace(/yu/gi, function(m){ return m === m.toUpperCase() ? "Ю" : "ю"; });
    w = w.replace(/ye/gi, function(m){ return m === m.toUpperCase() ? "Е" : "е"; });
    w = w.replace(/Ў-KEEPER/g, "ў").replace(/Ғ-KEEPER/g, "ғ");
    var out = "";
    for (var i = 0; i < w.length; i++) {
      var c = w[i];
      out += LAT_TO_CYR[c] != null ? LAT_TO_CYR[c] : c;
    }
    return out;
  }

  function uzToCyr(obj) {
    var out = {};
    for (var k in obj) {
      if (Object.prototype.hasOwnProperty.call(obj, k)) {
        out[k] = latToCyrText(obj[k]);
      }
    }
    return out;
  }

  function latToCyrText(text) {
    if (typeof text !== "string") return text;
    // {placeholder} ichidagi matnni konvertatsiyadan himoyalaymiz (masalan {n} -> {н} bo'lib qolmasin)
    return text.replace(/\{([^{}]*)\}|([A-Za-z'ʻʼ`]+)/g, function(m, ph, word) {
      if (ph !== undefined) return "{" + ph + "}"; // placeholder o'zgarishsiz qoladi
      return latWordToCyr(word);
    });
  }

