  function getStored() {
    try {
      var v = localStorage.getItem(STORAGE_KEY);
      return v || null;
    } catch (e) {
      return null;
    }
  }

  function setStored(lang) {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) { /* ignore */ }
  }

  function getCurrentLang() {
    return displayLang(getStored() || "ru");
  }

  // t(key) -> current lang
  // t(key, params) -> current lang with substitution
  // t(key, lang) -> explicit lang
  // t(key, lang, params) -> both
  function t(key, arg2, arg3) {
    var lang, params;
    if (typeof arg2 === "string") {
      lang = arg2;
      params = arg3;
    } else {
      lang = getCurrentLang();
      params = arg2;
    }
    var dict = STRINGS[lang] || STRINGS.ru;
    var str = dict[key] != null ? dict[key] : (STRINGS.ru[key] != null ? STRINGS.ru[key] : key);
    if (params && typeof params === "object") {
      return str.replace(/\{(\w+)\}/g, function (m, k) {
        return params[k] != null ? String(params[k]) : m;
      });
    }
    return str;
  }

  // tn(key, count) -> choose plural form for count (en: one/other only)
  // For richer plural rules, pass an object: tn(key, {one: "...", few: "...", many: "...", other: "..."}, count)
  function tn(key, count, opts) {
    var lang = getCurrentLang();
    var params = opts && typeof opts === "object" ? opts : {};
    var c = Number(count) || 0;
    // Eng va Rus uchun sodda: c==1 ? one : other
    if (lang === "en" || lang === "uz" || lang === "uz_cyr") {
      params.n = c;
      return t(key, params);
    }
    if (lang === "ru") {
      var mod10 = c % 10, mod100 = c % 100;
      var form = (mod10 === 1 && mod100 !== 11) ? "one"
               : (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) ? "few"
               : "many";
      var choice = params[form] || params.other || "";
      return choice.replace(/\{n\}/g, c);
    }
    return t(key, params);
  }

  function applyToElement(el, lang) {
    if (el.hasAttribute("data-i18n")) {
      var key = el.getAttribute("data-i18n");
      var hasChildElements = el.querySelector(":scope > *") != null;
      if (!hasChildElements) {
        el.textContent = t(key, lang);
      } else {
        var textNode = null;
        for (var i = 0; i < el.childNodes.length; i++) {
          if (el.childNodes[i].nodeType === 3 && el.childNodes[i].textContent.trim().length > 0) {
            textNode = el.childNodes[i];
            break;
          }
        }
        if (textNode) textNode.textContent = t(key, lang);
      }
    }
    if (el.hasAttribute("data-i18n-placeholder")) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder"), lang));
    }
    if (el.hasAttribute("data-i18n-title")) {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title"), lang));
    }
  }

  // DOM supurishda chetlashtiriladigan elementlar (tarjima qilinmaydi)
  var SKIP_TAGS = { SCRIPT: 1, STYLE: 1, TEMPLATE: 1, CODE: 1, PRE: 1, TEXTAREA: 1, INPUT: 1, SELECT: 1, OPTION: 1, BR: 1, CANVAS: 1 };

  function shouldSkip(el) {
    if (!el || el.nodeType !== 1) return true;
    if (el.id === "lang-btn" || el.id === "lang-dropdown-menu") return true;
    if (el.closest && el.closest("#lang-dropdown-menu, #lang-btn")) return true;
    if (SKIP_TAGS[el.tagName]) return true;
    if (el.hasAttribute && el.getAttribute("data-i18n-skip") !== null) return true;
    if (el.closest && el.closest("[data-i18n-skip]")) return true;
    return false;
  }

  // Barcha matn tugunlarini (text nodes) aylab, manba tilidagi matnni tarjima qilamiz.
  // Har bir tugunning ASL matni (node.__i18nSrc) saqlanadi, shuning uchun tilni
  // bir necha marta o'zgartirganda ham asl (ruscha) matndan tarjima qilinadi.
  // So'z-ma'so'z zaxira (token-level fallback):
  // Agar butun matn kalit bo'lmasa, kirillik so'zlarni alohida tarjima qilamiz.
  // Bu "{n} файлов", "Готово · код X · Y мс", "N файлов · M КБ" kabi
  // dinamik (app.js tomonidan injekt qilingan) qatorlarni iloji boricha tarjima qiladi.
  function isCyrChar(ch) {
    if (!ch) return false;
    var c = ch.charCodeAt(0);
    return c >= 0x0400 && c <= 0x04FF;
  }
  function translateTokens(core, lang) {
    var re = /([\u0400-\u04FF]+(?:[ \-'\u2019][\u0400-\u04FF]+)*)|([^\u0400-\u04FF]+)/g;
    var out = "";
    var changed = false;
    var m;
    while ((m = re.exec(core)) !== null) {
      if (m[1] != null) {
        var tok = m[1];
        var tr = translateText(tok, lang);
        if (tr !== tok) { changed = true; out += tr; }
        else if (/\s/.test(tok)) {
          var words = tok.split(/(\s+)/);
          var wchanged = false, wout = "";
          for (var i = 0; i < words.length; i++) {
            var w = words[i];
            if (w && isCyrChar(w.charAt(0))) {
              var wt = translateText(w, lang);
              if (wt !== w) { wchanged = true; wout += wt; }
              else wout += w;
            } else wout += w;
          }
          if (wchanged) { changed = true; out += wout; }
          else out += tok;
        } else out += tok;
      } else {
        out += m[2];
      }
    }
    return changed ? out : core;
  }

  function sweepTextNodes(lang) {
    if (!document.createTreeWalker) return;
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
    var node;
    while ((node = walker.nextNode())) {
      var parent = node.parentNode;
      if (!parent || shouldSkip(parent)) continue;
      if (parent.hasAttribute && parent.hasAttribute("data-i18n")) continue; // applyToElement boshqaradi
      if (node.__i18nSrc === undefined) node.__i18nSrc = node.nodeValue;
      var src = node.__i18nSrc;
      var ws = /^(\s*)([\s\S]*?)(\s*)$/.exec(src);
      if (!ws || !ws[2]) continue; // faqat bo'shliq tugunlari — o'tkazib yuboramiz
      // Bosh/kuy qismidagi bo'shliqlarni saqlab qolamiz, aks holda <strong>/<b>
      // bilan ajratilgan jumlalarni ("Enteryuborish" kabi) yopishib qoladi.
      var normCore = normalizeWs(ws[2]);
      var core = translateText(normCore, lang);
      if (core === normCore) {
        // Butun tugun kalit emas -> so'z-ma'so'z zaxira (dinamik qatorlar uchun)
        core = translateTokens(ws[2], lang);
      }
      var tr = ws[1] + core + ws[3];
      if (tr !== node.nodeValue) node.nodeValue = tr;
    }
  }

  // title / placeholder / aria-label atributlarini tarjima qilamiz.
  function sweepAttributes(lang) {
    var all = document.querySelectorAll("body *");
    for (var i = 0; i < all.length; i++) {
      var el = all[i];
      if (shouldSkip(el)) continue;
      var attrs = ["title", "placeholder", "aria-label"];
      for (var a = 0; a < attrs.length; a++) {
        var attr = attrs[a];
        if (!el.hasAttribute(attr)) continue;
        var cur = el.getAttribute(attr);
        if (!cur) continue;
        if (!el.__i18nAttr) el.__i18nAttr = {};
        if (el.__i18nAttr[attr] === undefined) el.__i18nAttr[attr] = cur;
        var tr = translateText(el.__i18nAttr[attr], lang);
        if (tr !== cur) el.setAttribute(attr, tr);
      }
    }
  }

  function applyLanguage(lang) {
    lang = displayLang(lang);
    // 1) data-i18n bilan belgilangan elementlar (asosiy kalitlar)
    var nodes = document.querySelectorAll("[data-i18n],[data-i18n-placeholder],[data-i18n-title]");
    for (var i = 0; i < nodes.length; i++) {
      applyToElement(nodes[i], lang);
    }
    // 2) qolgan barcha qattiq yozilgan (ruscha/inglizcha) matnlarni supurib tarjima qilish
    sweepTextNodes(lang);
    sweepAttributes(lang);
    document.documentElement.setAttribute("lang", lang === "uz_cyr" ? "uz" : lang);
    syncLangMenuActive(lang);
    return lang;
  }


  function syncToBackend(lang) {
    try {
      fetch("/api/settings/language", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ language: lang })
      }).catch(function () { /* offline bo'lsa e'tibor bermaymiz */ });
    } catch (e) { /* ignore */ }
  }

  function buildLangMenu(menu, lang) {
    if (!menu) return;
    menu.innerHTML = "";
    var opts = [
      { v: "en", l: "lang_opt_en" },
      { v: "uz", l: "lang_opt_uz" },
      { v: "uz_cyr", l: "lang_opt_uz_cyr" },
      { v: "ru", l: "lang_opt_ru" }
    ];
    opts.forEach(function (o) {
      var item = document.createElement("button");
      item.type = "button";
      item.className = "menu-dropdown-item lang-option";
      item.setAttribute("role", "menuitemradio");
      item.setAttribute("data-lang", o.v);
      item.setAttribute("data-i18n", o.l);
      item.textContent = t(o.l, lang);
      if (o.v === lang) item.classList.add("active");
      menu.appendChild(item);
    });
  }

  function syncLangMenuActive(lang) {
    var menu = document.getElementById("lang-dropdown-menu");
    if (!menu) return;
    var items = menu.querySelectorAll(".lang-option");
    for (var i = 0; i < items.length; i++) {
      if (items[i].getAttribute("data-lang") === lang) items[i].classList.add("active");
      else items[i].classList.remove("active");
    }
  }

  function init() {
    var langBtn = document.getElementById("lang-btn");
    var langMenu = document.getElementById("lang-dropdown-menu");
    var lang = displayLang(getStored() || "ru");
    if (langMenu) buildLangMenu(langMenu, lang);
    applyLanguage(lang);

    fetch("/api/settings/language")
      .then(function (r) { return r.json(); })
      .then(function (data) {
        var backendLang = displayLang((data && data.language) || "ru");
        var localLang = getStored();
        var finalLang = localLang ? displayLang(localLang) : backendLang;
        if (localLang && localLang !== backendLang) {
          syncToBackend(finalLang);
        }
        applyLanguage(finalLang);
        setStored(finalLang);
        if (langMenu) buildLangMenu(langMenu, finalLang);
      })
      .catch(function () { /* backend yo'q — localStorage bilan davom */ });

    if (langBtn && langMenu) {
      // Portal: topbar overflow menyuni kesib tashlamasligi uchun <body> ga ko'chiramiz
      document.body.appendChild(langMenu);
      langMenu.classList.add("portaled");

      var positionLangMenu = function () {
        var r = langBtn.getBoundingClientRect();
        var menuW = langMenu.offsetWidth || 200;
        var menuH = langMenu.offsetHeight || 180;
        var margin = 8;
        var left = r.left;
        left = Math.min(left, window.innerWidth - menuW - margin);
        left = Math.max(margin, left);
        var top = r.bottom + margin;
        if (top + menuH > window.innerHeight - margin) {
          top = Math.max(margin, r.top - menuH - margin);
        }
        langMenu.style.setProperty("top", Math.round(top) + "px", "important");
        langMenu.style.setProperty("left", Math.round(left) + "px", "important");
        langMenu.style.setProperty("right", "auto", "important");
      };

      var closeLangMenu = function () {
        langMenu.classList.add("hidden");
        langBtn.setAttribute("aria-expanded", "false");
      };
      var openLangMenu = function () {
        langMenu.classList.remove("hidden");
        positionLangMenu();
        langBtn.setAttribute("aria-expanded", "true");
      };

      langBtn.setAttribute("aria-haspopup", "true");
      langBtn.setAttribute("aria-expanded", "false");

      langBtn.addEventListener("click", function (e) {
        e.preventDefault();
        e.stopPropagation();
        if (langMenu.classList.contains("hidden")) openLangMenu();
        else closeLangMenu();
      });

      langMenu.addEventListener("click", function (e) {
        var item = e.target.closest(".lang-option");
        if (!item) return;
        e.preventDefault();
        e.stopPropagation();
        var chosen = displayLang(item.getAttribute("data-lang"));
        setStored(chosen);
        applyLanguage(chosen);
        syncToBackend(chosen);
        closeLangMenu();
      });

      document.addEventListener("click", function (e) {
        if (!langBtn.contains(e.target) && !langMenu.contains(e.target)) closeLangMenu();
      });
      document.addEventListener("keydown", function (e) {
        if (e.key === "Escape") closeLangMenu();
      });

      var keepAligned = function () {
        if (!langMenu.classList.contains("hidden")) positionLangMenu();
      };
      window.addEventListener("resize", keepAligned);
      window.addEventListener("scroll", keepAligned, true);
      var topbarEl = document.querySelector(".hud-topbar");
      if (topbarEl) topbarEl.addEventListener("scroll", keepAligned, { passive: true });
    }

    if (window.MutationObserver) {
      var observer = new MutationObserver(function (mutations) {
        var needApply = false;
        for (var mi = 0; mi < mutations.length; mi++) {
          var m = mutations[mi];
          if (m.type !== "childList" || !m.addedNodes.length) continue;
          for (var i = 0; i < m.addedNodes.length; i++) {
            var n = m.addedNodes[i];
            if (n.nodeType !== 1) continue;
            // Suhbat oqimi / til-tanlov / kod bloklari ichidagi o'zgarishlarni o'tkazib yuboramiz
            if (shouldSkip(n)) continue;
            if (n.closest && n.closest("[data-i18n-skip], #lang-dropdown-menu, #lang-btn, pre, code, script, style")) continue;
            needApply = true;
            break;
          }
          if (needApply) break;
        }
        if (needApply) applyLanguage(getStored() || "ru");
      });
      observer.observe(document.body, { childList: true, subtree: true });
    }

    window.I18N = {
      t: t,
      tn: tn,
      translateText: translateText,
      applyLanguage: applyLanguage,
      getLang: getCurrentLang,
      setLang: function (l) { setStored(displayLang(l)); applyLanguage(l); syncToBackend(displayLang(l)); },
      getCurrentLang: getCurrentLang
    };
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
